import { launch, BASE, check, summary, uiLogin, openAdmin, TMP, sleep, setVal, click, clickText } from './lib.mjs';
import path from 'node:path';

const SHOTS = path.join(TMP, 'shots');
const adm = await launch({ port: 9333 });
const tr = await launch({ port: 9334 });
const p = adm.page, t = tr.page;
const real = (pg) => pg.errors.filter((e) => !/favicon\.ico/.test(e));
const toast = () => p.eval(`(document.getElementById('ad-toast-msg')||{}).textContent||''`);
const items = (panel) => p.eval(`[].map.call(document.querySelectorAll('#cpanel-${panel} .ad-list > li h4, #cpanel-${panel} .ad-list > li .ad-qtext'),function(h){return h.textContent})`);
const confirmDialog = async (label) => { await p.waitFor(`!!document.querySelector('dialog.ad-dialog[open]')`, 5000, 'dialog open'); await clickText(p, 'dialog.ad-dialog button', label); await sleep(1200); };
const itemBtn = (panel, title, match) => p.eval(`(function(){var li=[].filter.call(document.querySelectorAll('#cpanel-${panel} .ad-list > li'),function(l){return l.textContent.indexOf(${JSON.stringify(title)})!==-1})[0]; if(!li) return 'noitem'; var b=[].filter.call(li.querySelectorAll('button'),function(x){return ((x.getAttribute('aria-label')||'')+' '+x.textContent).indexOf(${JSON.stringify(match)})!==-1 && !x.disabled})[0]; if(!b) return 'nobtn'; b.click(); return 'ok'})()`);
const gotoCourse = async (tab) => { await p.eval(`location.hash='#courses/capm${tab && tab !== 'files' ? '/' + tab : ''}'`); await p.waitFor(`!!document.querySelector('#cpanel-files')`, 15000, 'capm page'); await sleep(700); };
const traineeSees = async (tab) => {
  await t.goto(BASE + '/dashboard/#course=capm&tab=' + tab, 600);
  await t.eval('location.reload()');
  await t.waitFor(`!!document.querySelector('.pf-tabs') || !!document.querySelector('.pf-empty')`, 20000, 'trainee course view');
  await sleep(700);
  return t.eval(`(function(){return {files:[].map.call(document.querySelectorAll('#cpanel-files .pf-item h3'),function(h){return h.textContent}), videos:[].map.call(document.querySelectorAll('#cpanel-videos .pf-video h3'),function(h){return h.textContent}), vlinks:[].map.call(document.querySelectorAll('#cpanel-videos .pf-vlink'),function(a){return a.href}), iframes:[].map.call(document.querySelectorAll('#cpanel-videos iframe'),function(f){return f.src}), questions:document.querySelectorAll('#cpanel-quiz .pf-q').length, counts:[].map.call(document.querySelectorAll('.pf-tabs .pf-count'),function(c){return c.textContent})}})()`);
};
const QF = '#cpanel-questions form.ad-qform';
try {
  await uiLogin(t, 'a');
  await uiLogin(p, 'admin');
  await openAdmin(p, 'courses/capm/questions', 1500);
  await p.waitFor(`!!document.querySelector('#cpanel-questions')`, 15000, 'capm questions');
  await click(p, '#ctab-questions');
  await clickText(p, '#cpanel-questions button', 'إضافة سؤال');
  await sleep(300);
  await setVal(p, QF + ' textarea', 'ما اسم أول مجال معرفة؟ (سؤال P4)');
  await p.eval(`(function(){var inp=document.querySelectorAll(${JSON.stringify(QF + ' .ad-optrow input[type=text]')}); function s(i,v){i.value=v;i.dispatchEvent(new Event('input',{bubbles:true}));} s(inp[0],'الخيار أ'); s(inp[1],'الخيار ب');})()`);
  await clickText(p, QF + ' button', 'إضافة خيار');
  await p.eval(`(function(){var inp=document.querySelectorAll(${JSON.stringify(QF + ' .ad-optrow input[type=text]')}); var i=inp[2]; i.value='الخيار ج'; i.dispatchEvent(new Event('input',{bubbles:true})); document.querySelectorAll(${JSON.stringify(QF + ' .ad-optrow input[type=radio]')})[2].click(); var ta=document.querySelectorAll(${JSON.stringify(QF + ' textarea')}); ta[1].value='الشرح: هذا شرح الإجابة الصحيحة'; ta[1].dispatchEvent(new Event('input',{bubbles:true}));})()`);
  /* one empty option -> rejected */
  await clickText(p, QF + ' button', 'إضافة خيار');
  await clickText(p, QF + ' button', 'إضافة السؤال');
  await sleep(500);
  check('empty option rejected', ((await p.eval(`(document.querySelector(${JSON.stringify(QF + ' .pf-msg.err')})||{}).textContent||''`)) || '').indexOf('نصًا لكل خيار') !== -1);
  await p.eval(`(function(){var r=document.querySelectorAll(${JSON.stringify(QF + ' .ad-optrow')}); r[r.length-1].querySelector('button').click();})()`);
  await clickText(p, QF + ' button', 'إضافة السؤال');
  await p.waitFor(`document.querySelectorAll('#cpanel-questions .ad-list > li').length===1`, 10000, 'question added');
  check('question added (3 options, correct = third)', await p.eval(`(function(){var o=document.querySelectorAll('#cpanel-questions .ad-qopt'); return o.length===3 && o[2].classList.contains('ok')})()`), await toast());
  let seen = await traineeSees('quiz');
  check('trainee sees the new question in the quiz tab', seen.questions === 1 && seen.counts[2] === '(1)', JSON.stringify(seen));
  await t.eval(`document.querySelectorAll('#cpanel-quiz .pf-q input[type=radio]')[2].click()`);
  await t.eval(`document.querySelector('#cpanel-quiz form button[type=submit]').click()`);
  await t.waitFor(`!!document.querySelector('#cpanel-quiz .pf-result')`, 15000, 'quiz result');
  check('trainee quiz graded server-side: 1 / 1', (await t.eval(`document.querySelector('#cpanel-quiz .pf-result .big').textContent`)).replace(/\s/g, '') === '1/1');
  await sleep(900);
  check('trainee review shows the explanation text', await t.eval(`!!document.querySelector('#cpanel-quiz .pf-expl') && document.querySelector('#cpanel-quiz .pf-expl').textContent.indexOf('الشرح: هذا شرح الإجابة الصحيحة')!==-1`));
  /* edit + unpublish + republish */
  await gotoCourse('questions');
  await click(p, '#ctab-questions');
  await itemBtn('questions', 'ما اسم أول مجال', 'تعديل');
  await sleep(400);
  await setVal(p, QF + ' textarea', 'ما اسم أول مجال معرفة؟ (سؤال P4 معدّل)');
  await clickText(p, QF + ' button', 'حفظ السؤال');
  await sleep(1500);
  check('question edited', (await items('questions')).some((x) => x.indexOf('معدّل') !== -1), JSON.stringify(await items('questions')));
  await itemBtn('questions', 'سؤال P4 معدّل', 'إخفاء');
  await sleep(1500);
  seen = await traineeSees('quiz');
  check('unpublished question disappears for the trainee', seen.questions === 0, JSON.stringify(seen));
  await gotoCourse('questions');
  await click(p, '#ctab-questions');
  await itemBtn('questions', 'سؤال P4 معدّل', 'نشر');
  await sleep(1200);
  /* second question + reorder */
  await clickText(p, '#cpanel-questions button', 'إضافة سؤال');
  await sleep(300);
  await setVal(p, QF + ' textarea', 'سؤال ثانٍ P4');
  await p.eval(`(function(){var inp=document.querySelectorAll(${JSON.stringify(QF + ' .ad-optrow input[type=text]')}); function s(i,v){i.value=v;i.dispatchEvent(new Event('input',{bubbles:true}));} s(inp[0],'نعم'); s(inp[1],'لا');})()`);
  await clickText(p, QF + ' button', 'إضافة السؤال');
  await p.waitFor(`document.querySelectorAll('#cpanel-questions .ad-list > li').length===2`, 10000, 'second q');
  await itemBtn('questions', 'سؤال ثانٍ P4', 'للأعلى');
  await sleep(1500);
  const qs = await items('questions');
  check('question reorder: second question moved to first place', /ثانٍ/.test(qs[0]), JSON.stringify(qs));
  await p.shot(path.join(SHOTS, 'courses-capm-questions.png'), true);
  console.log('trainee errors:', JSON.stringify(real(t)));
  check('trainee browser: no console errors', real(t).length === 0, JSON.stringify(real(t)));
} catch (e) { console.log('ERR', e.message); try { await p.shot(path.join(SHOTS, 'err-adm.png')); } catch (x) { /* ignore */ } }
console.log('admin errors:', JSON.stringify(real(p)));
check('admin browser: no console errors', real(p).length === 0, JSON.stringify(real(p)));
summary();
await adm.close(); await tr.close();
